-- Dravonix WhatsApp AI Platform
-- Phase 6C: staging billing automation foundation. Migrations 28 and 29 are
-- immutable and are never touched here -- this migration only builds
-- forward. All new RPCs below are service_role-only (called exclusively by
-- the new apps/workers/billing-scheduler cron Worker), except the one
-- Super Admin read RPC at the end, which follows the exact
-- current_platform_role() = 'super_admin' gating pattern already
-- established by admin_assign_plan (migration 17).
--
-- Scope (deliberately staying inside what Phase 6C asked for -- no
-- Super Admin billing UI, no WhatsApp billing notifications, no discounts/
-- proration/refunds/taxes):
--
--   1. invoices.billing_period_start / billing_period_end -- the
--      authoritative billing-cycle identity for a subscription invoice
--      (Phase 4). A partial unique index on
--      (company_id, billing_period_start, billing_period_end) is the
--      idempotency guarantee: a scheduler that runs twice, retries, or
--      overlaps can never create two invoices for the same cycle -- the
--      second attempt hits unique_violation and is caught as a no-op,
--      exactly mirroring how migration 28/29 already treat
--      payments.provider_reference and payment_attempts'
--      unique(provider, provider_event_id).
--
--   2. billing_invoice_number_seq -- a real Postgres sequence backing a
--      production-safe invoice-number format (DRV-<year>-<6 digits>).
--      Sequences are safe under arbitrary concurrency by construction; no
--      test fixture invoice number (INV-STAGING-TEST-0001 etc.) is ever
--      produced by this path.
--
--   3. billing_reminders -- one idempotency row per (invoice, lifecycle
--      stage, channel). The reminder scheduler checks this table before
--      ever creating a notification, so a rerun/retry/overlap can never
--      send (or record) the same reminder twice.
--
--   4. Five new RPCs, in the order the daily scheduler calls them:
--      generate_due_subscription_invoices, advance_overdue_subscriptions,
--      suspend_expired_grace_subscriptions, send_due_billing_reminders,
--      and the Super-Admin-only read RPC admin_billing_lifecycle_overview.
--      Every state transition uses an existing canonical
--      subscription_state/SubscriptionEvent value from
--      packages/billing/src/stateMachine.ts -- none is invented. Every
--      write is company-scoped by construction (looked up from the
--      subscription/invoice row itself, never a parameter), matching the
--      tenant-isolation discipline already established in migrations 28/29.
--
--   5. Grace-period duration: plan_versions.grace_period_days already
--      exists (migration 7, default 5) with a matching pure calculator,
--      packages/billing/src/gracePeriod.ts's computeGracePeriodEnd -- both
--      unit-tested but never wired into any production code path before
--      this migration (confirmed by repo-wide audit). This migration is
--      the first thing to actually consume that column; no new duration is
--      invented, and the SQL mirrors the exact
--      `startedAt + gracePeriodDays days` arithmetic the TS helper already
--      defines.
--
--   6. Decision point (payment_due -> grace_period timing): the state
--      machine models `payment_due` and `grace_period` as two distinct
--      states connected by `grace_period_started`, but no existing ADR or
--      doc (checked docs/architecture/adr-0006 and
--      BILLING_AND_SUSPENSION.md) defines how long a subscription should
--      sit in bare `payment_due` before `grace_period_started` fires.
--      Resolved here: advance_overdue_subscriptions transitions
--      active/trial -> payment_due and immediately -> grace_period in the
--      same scheduler pass (two real subscription_events rows, using both
--      canonical events faithfully -- payment_due is momentary/transient,
--      not a separately-timed waiting state), because the only duration
--      this codebase actually defines anywhere is the grace period itself
--      (plan_versions.grace_period_days). Inventing a second, undocumented
--      "how long to wait in payment_due" duration would be exactly the
--      kind of invented business rule Phase 6C says not to guess.
--
--   7. Trial first-invoice timing (Phase 26): no existing doc defines this.
--      Resolved here identically to the renewal-invoice rule (7 days
--      before the relevant period end) for consistency -- trial and
--      subscription renewal invoices are generated by the exact same RPC,
--      keyed off current_period_end regardless of whether the subscription
--      is currently `trial` or `active`.
--
--   8. Email sending: Phase 6C's own instruction is to STOP before sending
--      automated external emails if no staging-safety mechanism exists.
--      A repo-wide audit found none (no environment guard, no recipient
--      override, on any customer-facing email send path). This migration
--      and the accompanying Worker therefore only ever produce
--      DB-persisted, dashboard-visible reminder state (billing_reminders +
--      an in-app `notifications` row) -- no email provider is ever
--      invoked from this migration or from apps/workers/billing-scheduler.
--      A render-only, fully unit-tested email template is added in
--      packages/email for later use once a real staging-safety mechanism
--      exists; wiring it to an actual send is explicitly out of scope here.

-- ---------------------------------------------------------------------------
-- 1. Invoice billing-cycle identity.
-- ---------------------------------------------------------------------------

alter table invoices add column billing_period_start date;
alter table invoices add column billing_period_end date;

comment on column invoices.billing_period_start is
  'Company-local calendar date the billed subscription period starts. Null for non-subscription invoices (service_charge/usage_overage) and for any invoice created before migration 30. Set once, at generation time, from subscriptions.current_period_start converted via companies.timezone -- never recomputed.';
comment on column invoices.billing_period_end is
  'Company-local calendar date the billed subscription period ends (this is also the invoice due_date). Together with company_id, the authoritative billing-cycle identity: see invoices_subscription_cycle_key below.';

create unique index invoices_subscription_cycle_key on invoices (company_id, billing_period_start, billing_period_end)
  where kind = 'subscription' and billing_period_start is not null and billing_period_end is not null;

comment on index invoices_subscription_cycle_key is
  'Phase 6C invoice-generation idempotency: at most one subscription invoice may ever exist for a given company + billing cycle, regardless of how many times the scheduler runs, retries, or overlaps. Postgres treats every NULL as distinct under a plain unique index (same reasoning as payments_provider_reference_key in migration 28), so pre-existing rows with null billing_period_start/end are completely unaffected.';

