create sequence billing_invoice_number_seq;

comment on sequence billing_invoice_number_seq is
  'Backs the DRV-<year>-<6 digits> invoice number format (Phase 6C). A real Postgres sequence is used specifically because it is safe under arbitrary concurrency by construction -- no advisory lock or row lock is needed to avoid a collision. Test/demo fixtures (e.g. INV-STAGING-TEST-0001) are unrelated hand-authored strings and never collide with this format.';

