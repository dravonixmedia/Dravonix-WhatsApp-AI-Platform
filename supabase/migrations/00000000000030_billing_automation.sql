create table billing_reminders (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references companies (id) on delete cascade,
  invoice_id uuid not null references invoices (id) on delete cascade,
  stage billing_reminder_stage not null,
  channel text not null default 'in_app',
  sent_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  unique (invoice_id, stage, channel)
);

comment on table billing_reminders is
  'Phase 6C reminder idempotency: one row per (invoice, lifecycle stage, channel) ever created. send_due_billing_reminders checks this table before creating any notification, so a scheduler rerun/retry/overlap can never send (or even record) the same reminder twice. channel is a plain text column (not an enum) so a future channel can be added without a migration -- mirrors notifications.category''s existing text-not-enum convention (migration 8).';

create index billing_reminders_company_id_idx on billing_reminders (company_id);

